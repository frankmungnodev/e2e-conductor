import { SHELL_TARGET, type TargetConfig } from "./config.ts"
import { stepsWithoutIds } from "./db/drafts.ts"
import type { Scenario, Step } from "./db/scenarios.ts"
import type { StepGroup } from "./db/step-groups.ts"
import type { StepPreset } from "./db/step-presets.ts"
import type { Problem } from "./problems.ts"
import type { CheckedEnvironment } from "./strict-check.ts"
import {
  ACTIONS,
  COMMON_ACTION_FIELDS,
  COMMON_STEP_FIELDS,
  DRIVER_STEP_FIELDS,
  type DriverName,
  JSON_MATCH_OPERATORS,
  NO_EFFECT_ACTION_FIELDS,
  PLACEHOLDER_NAMESPACES,
  PROBLEM_CODES,
  REMOVED_FIELDS,
  STEP_NEEDS,
} from "./vocabulary.ts"

/** What the kit tells an agent about the project. Names only: no env values, fixture commands or service URLs. */
export type KitFacts = {
  /** The environments `e2e save` checks drafts against. */
  environments: CheckedEnvironment[]
  /** `no-draft-environment` when no environment allows drafts. */
  notices: Problem[]
  fixtures: string[]
  presets: StepPreset[]
  stepGroups: StepGroup[]
}

export const KIT_START = "<!-- e2e-kit:start -->"
export const KIT_END = "<!-- e2e-kit:end -->"

const KIT_PATH = ".e2e/agent/kit.md"
const VOCABULARY_PATH = ".e2e/agent/vocabulary.json"
const DRAFTS_FOLDER = ".e2e/drafts/<group>/"
const CHECK = 'e2e save --group <group> --prompt "<the person\'s request, word for word>" --agent <your name> --check --json'
const SAVE = 'e2e save --group <group> --prompt "<the same request>" --agent <your name> --json'

/** The person-only actions, all in the e2e UI. */
const PERSON_ONLY: Array<{ name: string; note: string }> = [
  { name: "Run batch", note: "runs every draft of a group" },
  { name: "Keep and Keep all passing", note: "a draft needs a pass on its current content first" },
  { name: "Bug found", note: "sets a failing draft aside as a real app bug; you cannot change it after that" },
  { name: "Discard", note: "a draft or a whole group" },
  { name: "Allow drafts on an environment", note: "the draft mark" },
]

/** Write paths an agent must never use: they skip the draft state and the strict check. */
const FORBIDDEN = "`POST /api/scenarios`, `e2e import`, or the SQLite database (`.e2e/e2e.db`) directly"

/** Action fields the kit teaches: the ones the action reads, without fields no driver reads. */
const taughtFields = (fields: string[]) => fields.filter((field) => !(field in NO_EFFECT_ACTION_FIELDS))

/** `vocabulary.json`: the step vocabulary for agents and tools, generated from `src/vocabulary.ts`. */
export function renderVocabulary(): string {
  const drivers = Object.fromEntries(
    (Object.keys(ACTIONS) as DriverName[]).map((driver) => [
      driver,
      {
        stepFields: DRIVER_STEP_FIELDS[driver],
        stepNeeds: STEP_NEEDS[driver],
        actions: ACTIONS[driver].map((spec) => ({ name: spec.name, aliases: spec.aliases, fields: taughtFields(spec.fields) })),
      },
    ]),
  )
  const vocabulary = {
    generatedBy: "e2e kit",
    commonStepFields: COMMON_STEP_FIELDS,
    commonActionFields: COMMON_ACTION_FIELDS,
    drivers,
    assert: ["status", "exit_code", "output_contains", "json_match"],
    jsonMatchOperators: JSON_MATCH_OPERATORS,
    placeholderNamespaces: PLACEHOLDER_NAMESPACES,
    removedFields: REMOVED_FIELDS,
    problemCodes: PROBLEM_CODES,
  }
  return `${JSON.stringify(vocabulary, null, 2)}\n`
}

/** The block `e2e kit` keeps in the root `AGENTS.md` and `CLAUDE.md`, markers included, with no trailing newline. */
export function renderInstructionBlock(): string {
  return [
    KIT_START,
    "## End-to-end scenarios (generated by `e2e kit`)",
    "",
    `Before writing e2e scenarios, read \`${KIT_PATH}\`: it lists this project's targets, fixtures, env variable names and step vocabulary, with examples. Run \`e2e kit\` to refresh it.`,
    "",
    `- Write one scenario JSON file per scenario to \`${DRAFTS_FOLDER}<scenario-id>.json\`.`,
    `- Check them with \`${CHECK}\`, fix every problem, then save them as drafts with \`${SAVE}\`.`,
    `- Only the person, in the e2e UI: ${PERSON_ONLY.map((action) => action.name).join(", ")}.`,
    `- Never write scenarios through ${FORBIDDEN}.`,
    KIT_END,
  ].join("\n")
}

/** `kit.md`: everything an agent needs to write scenarios this project's `e2e save` accepts. */
export function renderKit(facts: KitFacts): string {
  const lines: string[] = [
    "# e2e agent kit",
    "",
    `Generated by \`e2e kit\` from this project's e2e config. Do not edit it: run \`e2e kit\` again after the config changes. The machine-readable vocabulary is in \`${VOCABULARY_PATH}\`.`,
    "",
    "## How to add scenarios",
    "",
    `1. Pick a short group slug for the person's request, such as \`checkout\`. Write one scenario JSON file per scenario to \`${DRAFTS_FOLDER}\`. The file name, without \`.json\`, is the scenario id.`,
    `2. Check the batch: \`${CHECK}\`. It stores nothing. \`e2e save\` finds the project from any folder inside it; if \`e2e\` is not on the PATH, run it through the project's package runner (for example \`npx e2e\`).`,
    "3. Fix every problem it reports and check again until `ok` is true. Each problem names the file, the step (`stepIndex`, `pointer`), a `code`, the `allowed` values when there is a fixed set, and a `hint`.",
    `4. Save: \`${SAVE}\`. A save is all or nothing: any problem stores no file.`,
    "5. Tell the person the group is saved. They run it and decide what to keep in the e2e UI.",
    "",
    "Saving a file again updates its draft. Saving a file whose id is a kept scenario stores a revision (`<id>@draft`) and leaves the kept scenario running unchanged until the person keeps the revision.",
    "",
    "## Rules",
    "",
    "- Name targets and fixtures exactly as listed below. Use `shell` for local commands.",
    "- No raw URLs, hosts, ports or device serials: a `url` is a path relative to the target's service, such as `/login`. The environment supplies the rest.",
    "- Never point a scenario at production. Drafts run only on environments the person allowed for drafts.",
    "- `${env.NAME}` may use only the env variable names listed for the environments below.",
    "- `${ctx.name}` must be set by the scenario's `vars` or extracted by an earlier step's `extract`.",
    "- Steps from presets and step groups are copied into the scenario: no scenario field references them.",
    "",
    "## What only the person does",
    "",
    "These happen in the e2e UI, by the person. Do not try to do them:",
    "",
    ...PERSON_ONLY.map((action) => `- ${action.name} (${action.note})`),
    "",
    `Never write scenarios through ${FORBIDDEN}. \`e2e save\` is the only write path for agents.`,
    "",
    ...renderProject(facts),
    ...renderExamples(facts),
    ...renderVocabularyText(),
  ]
  return `${lines.join("\n").trimEnd()}\n`
}

function renderProject(facts: KitFacts): string[] {
  const lines = ["## This project", ""]
  for (const notice of facts.notices) lines.push(`Note: ${notice.message}. The person can allow drafts on an environment in the e2e UI.`, "")
  lines.push(
    `\`e2e save\` checks drafts against: ${facts.environments.map((environment) => `\`${environment.name}\``).join(", ")}. A target or env variable must exist in each of them.`,
    "",
  )
  for (const environment of facts.environments) {
    lines.push(`### Environment \`${environment.name}\``, "", "Targets:", "")
    for (const [name, target] of Object.entries(environment.targets)) lines.push(`- \`${name}\` (${target.driver})`)
    lines.push(`- \`${SHELL_TARGET}\` (shell: local commands)`, "")
    const vars = environment.envVars.map((name) => `\`${name}\``).join(", ")
    lines.push(`Env variable names: ${vars || "none"}`, "")
  }
  lines.push("### Fixtures", "", "Name them in a scenario's `setup` to reset or seed state before the first step.", "")
  lines.push(...(facts.fixtures.length > 0 ? facts.fixtures.map((name) => `- \`${name}\``) : ["None configured."]), "")
  lines.push("### Step presets and step groups", "", "Copy their steps into a scenario's `steps`; no scenario field references them.", "")
  if (facts.presets.length === 0 && facts.stepGroups.length === 0) lines.push("None saved.", "")
  for (const preset of facts.presets) lines.push(...reusable(`Preset "${preset.name}"`, preset.description, [preset.step]))
  for (const group of facts.stepGroups) lines.push(...reusable(`Step group "${group.name}"`, group.description, group.steps))
  return lines
}

function reusable(title: string, description: string | undefined, steps: Step[]): string[] {
  // Stored step and action ids are dropped: a draft save drops them anyway.
  const copy = stepsWithoutIds(steps)
  return [`#### ${title}`, "", ...(description ? [description, ""] : []), "```json", JSON.stringify(copy, null, 2), "```", ""]
}

/** Two or three example scenarios on the project's own targets, one per driver, that pass the strict check. */
function renderExamples(facts: KitFacts): string[] {
  const targets = facts.environments.reduce<Record<string, TargetConfig>>(
    (common, environment, index) =>
      index === 0 ? { ...environment.targets } : Object.fromEntries(Object.entries(common).filter(([name]) => environment.targets[name])),
    {},
  )
  const firstOf = new Map<string, string>()
  for (const [name, target] of Object.entries(targets)) if (!firstOf.has(target.driver)) firstOf.set(target.driver, name)
  const examples: Omit<Scenario, "id">[] = []
  for (const [driver, target] of firstOf) {
    if (examples.length === 3) break
    examples.push(example(driver as DriverName, target))
  }
  if (examples.length < 2) examples.push(example("shell", SHELL_TARGET))
  if (facts.fixtures.length > 0) examples[0] = { ...examples[0], setup: [facts.fixtures[0]] }

  const lines = [
    "## Examples",
    "",
    "Shapes to copy, built on this project's targets. The paths, selectors and values are placeholders: read the app's source for the real ones.",
    "",
  ]
  for (const each of examples) lines.push("```json", JSON.stringify(each, null, 2), "```", "")
  lines.push(
    "Passing a value between steps: extract it from the step result (for http, the JSON response body), then use it as `${ctx.name}` in a later step:",
    "",
    "```json",
    JSON.stringify({ extract: { itemId: "items[0].id" } }),
    JSON.stringify({ url: "/items/${ctx.itemId}" }),
    "```",
    "",
  )
  return lines
}

function example(driver: DriverName, target: string): Omit<Scenario, "id"> {
  switch (driver) {
    case "http":
      return {
        name: `${target} answers on its home path`,
        steps: [{ name: "Home path answers", target, method: "GET", url: "/", assert: { status: 200 } }],
      }
    case "web":
      return {
        name: `${target} home page shows its main content`,
        steps: [
          {
            name: "Open the home page",
            target,
            actions: [
              { action: "navigate", url: "/" },
              { action: "assert_visible", selector: "main" },
            ],
          },
        ],
      }
    case "mobile":
      return {
        name: `${target} opens on its first screen`,
        steps: [
          { name: "Launch the app", target, launch: "fresh" },
          { name: "First screen shows", target, actions: [{ action: "assert_visible", selector: "Welcome" }] },
        ],
      }
    case "shell":
      return {
        name: "A local command succeeds",
        steps: [{ name: "Node runs", target, command: "node --version", assert: { output_contains: "v" } }],
      }
  }
}

function renderVocabularyText(): string[] {
  const lines = [
    "## Scenario format",
    "",
    "A scenario file has `name` (required), `description`, `setup` (fixture names), `vars` (starting `${ctx.*}` values), `read_only` (true when the steps never change what the setup fixtures reset) and `steps` (required).",
    "",
    `Every step has \`name\` and \`target\`, and may have: ${COMMON_STEP_FIELDS.filter((field) => !["name", "target"].includes(field)).map((field) => `\`${field}\``).join(", ")}. Step and action ids are optional: a draft save drops them.`,
    "",
    "Checks go in the step's `assert`: `status` (http), `exit_code` and `output_contains` (shell), and `json_match` (path to an expected value, or an operator: " +
      `${JSON_MATCH_OPERATORS.map((operator) => `\`${operator}\``).join(", ")}). An http status of 400 or more fails unless \`assert.status\` expects it.`,
    "",
    "Placeholders:",
    "",
    ...Object.entries(PLACEHOLDER_NAMESPACES).map(([namespace, reads]) => `- \`\${${namespace}.<name>}\`: ${reads}`),
    "",
    `Removed fields, never write them: ${Object.keys(REMOVED_FIELDS).map((field) => `\`${field}\``).join(", ")}.`,
    "",
  ]
  for (const driver of Object.keys(ACTIONS) as DriverName[]) {
    lines.push(`### ${driver} steps`, "")
    lines.push(`Step fields: ${DRIVER_STEP_FIELDS[driver].map((field) => `\`${field}\``).join(", ")}. A step needs ${STEP_NEEDS[driver]}.`, "")
    lines.push(`Actions (each \`actions[]\` entry has \`action\` and optionally \`name\`):`, "")
    for (const spec of ACTIONS[driver]) {
      const fields = taughtFields(spec.fields).map((field) => `\`${field}\``).join(", ")
      const aliases = spec.aliases.length > 0 ? `; also written ${spec.aliases.map((alias) => `\`${alias}\``).join(", ")}` : ""
      lines.push(`- \`${spec.name}\`: ${fields || "no fields"}${aliases}`)
    }
    lines.push("")
  }
  lines.push(
    "## What `e2e save --json` reports",
    "",
    "One JSON document: `{ ok, mode, project, dbPath, checkedEnvironments, group, results, problems, notices }`, plus `error` when the command stopped before checking. On failure `results` is empty.",
    "",
    "Per file outcome: `created`, `updated`, `unchanged`, `revision-of` (with `revisionOf`, the kept id), `matches-kept` (the file equals its kept scenario, so nothing is stored).",
    "",
    "Exit codes: 0 stored (or clean with `--check`), 1 problems and nothing stored, 2 usage (no `--group`, a new group without `--prompt`, no files), 3 project or database error.",
    "",
    "Problem codes:",
    "",
    ...Object.entries(PROBLEM_CODES).map(([code, hint]) => `- \`${code}\`: ${hint}`),
  )
  return lines
}
